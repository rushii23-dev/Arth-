/**
 * The crop doctor's knowledge: the common diseases, pests and deficiencies of Arth's crops in
 * Maharashtra. The model only picks one of these ids from the photo; everything the farmer reads
 * comes from here, so the same problem always gets the same, checked advice.
 *
 * Chemical lines name the active ingredient only. Doses are never given: the farmer reads them
 * from the product label (Label reader), per SPEC §6 "Never guess a pesticide dose".
 *
 * English is the source. Hindi and Marathi live in conditions.hi.json / conditions.mr.json,
 * generated once by scripts/translate-conditions.ts and committed, so they never change at runtime.
 */

export type ConditionKind = 'disease' | 'pest' | 'deficiency' | 'healthy'

export interface Condition {
  id: string
  crop: string
  kind: ConditionKind
  name: string
  scientificName: string | null
  /** What it looks like in a photo: shown to the model, not to the farmer. */
  looksLike: string
  symptoms: string[]
  organic: string[]
  chemical: string[]
  prevention: string[]
}

const healthy = (crop: string, name: string): Condition => ({
  id: `${crop}.healthy`,
  crop,
  kind: 'healthy',
  name: `Healthy ${name.toLowerCase()}`,
  scientificName: null,
  looksLike: 'evenly green, firm leaves with no spots, holes, powder, curling or insects',
  symptoms: ['No sign of disease or pests in this photo.'],
  organic: [],
  chemical: [],
  prevention: [
    'Keep checking the field once a week, especially after rain or cloudy, humid days.',
    'Look at the underside of leaves too, where pests and mildew start.',
  ],
})

